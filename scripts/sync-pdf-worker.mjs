/**
 * Copies the pdf.js worker out of node_modules into `public/pdfjs/`, next to a
 * small shim that installs the upsert polyfill inside the worker's own global
 * scope before loading it.
 *
 * Why a static file rather than a bundled worker: pointing
 * `new Worker(new URL('./worker-entry.ts', import.meta.url))` at a TypeScript
 * entry makes Turbopack emit worker chunks that the client entry then fails to
 * load (ChunkLoadError). Serving a plain ESM file we control sidesteps the
 * bundler entirely and keeps the worker on our own origin, which the privacy
 * claim depends on.
 *
 * Runs automatically from `prebuild`; re-run by hand after upgrading pdfjs-dist.
 */

import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'public', 'pdfjs');

const pkg = JSON.parse(
  await readFile(require.resolve('pdfjs-dist/package.json'), 'utf8'),
);
const source = require.resolve('pdfjs-dist/build/pdf.worker.min.mjs');

await mkdir(outDir, { recursive: true });
await copyFile(source, join(outDir, 'pdf.worker.min.mjs'));

const shim = `/**
 * pdf.js worker shim — GENERATED by scripts/sync-pdf-worker.mjs. Do not edit.
 * pdfjs-dist ${pkg.version}
 *
 * pdfjs-dist 6.2 calls Map.prototype.getOrInsertComputed, which shipped in
 * Chrome 142 / Firefox 145 and is in no released Safari. A worker has its own
 * global scope, so the polyfill on the page does not reach it; without these
 * few lines every tool that rasterises a page throws
 * "getOrInsertComputed is not a function" on most real browsers.
 */
(() => {
  const define = (target, name, value) => {
    if (name in target) return;
    Object.defineProperty(target, name, {
      value, writable: true, enumerable: false, configurable: true,
    });
  };
  function getOrInsert(key, value) {
    if (this.has(key)) return this.get(key);
    this.set(key, value);
    return value;
  }
  function getOrInsertComputed(key, callbackfn) {
    if (typeof callbackfn !== 'function') {
      throw new TypeError('getOrInsertComputed: callbackfn is not a function');
    }
    if (this.has(key)) return this.get(key);
    const value = callbackfn(key);
    this.set(key, value);
    return value;
  }
  for (const ctor of [Map, WeakMap]) {
    define(ctor.prototype, 'getOrInsert', getOrInsert);
    define(ctor.prototype, 'getOrInsertComputed', getOrInsertComputed);
  }
})();

await import('./pdf.worker.min.mjs');
`;

await writeFile(join(outDir, 'worker.mjs'), shim, 'utf8');
console.log(`pdf.js worker ${pkg.version} synced to public/pdfjs/`);
